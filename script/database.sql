-- Bảng NHANVIEN phải tạo trước DONVI do DONVI tham chiếu đến NHANVIEN
CREATE TABLE NHANVIEN (
    MANV VARCHAR2(10) PRIMARY KEY,
    HOTEN VARCHAR2(100),
    PHAI VARCHAR2(5) CHECK (PHAI IN ('Nam', 'Nữ')),
    NGSINH DATE,
    LUONG NUMBER(10,2),
    PHUCAP NUMBER(10,2),
    DT VARCHAR2(20),
    VAITRO VARCHAR2(20) CHECK (VAITRO IN ('NVCB', 'GV', 'NV PĐT', 'NV PKT', 'NV TCHC', 'NV CTSV', 'TRGDV')),
    MADV VARCHAR2(10),
    COSO VARCHAR2(10 BYTE)
);

CREATE TABLE DONVI (
    MADV VARCHAR2(10) PRIMARY KEY,
    TENDV VARCHAR2(100),
    LOAIDV VARCHAR2(20) CHECK (LOAIDV IN ('Khoa', 'Phòng')),
    TRGDV VARCHAR2(10), -- Tham chiếu đến NHANVIEN
    CONSTRAINT fk_trgdv FOREIGN KEY (TRGDV) REFERENCES NHANVIEN(MANV)
);

-- Cập nhật lại khóa ngoại ở NHANVIEN sau khi DONVI tồn tại
ALTER TABLE NHANVIEN
ADD CONSTRAINT fk_nhanvien_donvi FOREIGN KEY (MADV) REFERENCES DONVI(MADV);

-- SINHVIEN
CREATE TABLE SINHVIEN (
    MASV VARCHAR2(10) PRIMARY KEY,
    HOTEN VARCHAR2(100),
    PHAI VARCHAR2(5) CHECK (PHAI IN ('Nam', 'Nữ')),
    NGSINH DATE,
    DCHI VARCHAR2(200),
    DT VARCHAR2(20),
    KHOA VARCHAR2(10), -- MADV tương ứng bên DONVI
    TINHTRANG VARCHAR2(20),
    COSO VARCHAR2(10 BYTE), 
    CONSTRAINT fk_sinhvien_khoa FOREIGN KEY (KHOA) REFERENCES DONVI(MADV)
);

-- HOCPHAN
CREATE TABLE HOCPHAN (
    MAHP VARCHAR2(10) PRIMARY KEY,
    TENHP VARCHAR2(100),
    SOTC NUMBER(2),
    STLT NUMBER(3),
    STTH NUMBER(3),
    MADV VARCHAR2(10),
    CONSTRAINT fk_hocphan_donvi FOREIGN KEY (MADV) REFERENCES DONVI(MADV)
);

-- MOMON
CREATE TABLE MOMON (
    MAMM VARCHAR2(10) PRIMARY KEY,
    MAHP VARCHAR2(10),
    MAGV VARCHAR2(10),
    HK NUMBER(1) CHECK (HK IN (1,2,3)),
    NAM NUMBER(4),
    CONSTRAINT fk_momon_hocphan FOREIGN KEY (MAHP) REFERENCES HOCPHAN(MAHP),
    CONSTRAINT fk_momon_giangvien FOREIGN KEY (MAGV) REFERENCES NHANVIEN(MANV)
);

-- DANGKY
CREATE TABLE DANGKY (
