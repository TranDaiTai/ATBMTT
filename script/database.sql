    CONSTRAINT fk_dangky_sv FOREIGN KEY (MASV) REFERENCES SINHVIEN(MASV),
    CONSTRAINT fk_dangky_mamon FOREIGN KEY (MAMM) REFERENCES MOMON(MAMM)
);

